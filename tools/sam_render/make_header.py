#!/usr/bin/env python3
"""Turn a raw SAM render (unsigned 8-bit, 22050 Hz) into firmware/desktop_pet/pet_me.h.

Adds a 30 ms silent lead-in so the opening "P" is not clipped by the amplifier waking up,
and writes a preview WAV next to the header output.
usage: make_header.py <in.raw> <out pet_me.h> <out preview.wav> "<phonetic string>" "<speed pitch throat mouth>"
"""
import sys, wave

raw, header, preview, phon, params = sys.argv[1:6]
data = bytes([128]) * 660 + open(raw, "rb").read()          # 660 samples = 30 ms @ 22050 Hz

with wave.open(preview, "wb") as w:
    w.setnchannels(1); w.setsampwidth(1); w.setframerate(22050); w.writeframes(data)

lines = [
    '// pet_me.h — the "pet me" clip played when the pet is neglected.',
    '// Generated by tools/sam_render (SAM speech synth, ESP8266SAM C core, run on the build host).',
    f'// Phonetic input "{phon}", speed/pitch/throat/mouth {params}; 30 ms silent lead-in.',
    '// Format: unsigned 8-bit mono, 22050 Hz, stored in flash. Played by PetAudio.',
    '#ifndef _PET_ME_h', '#define _PET_ME_h', '#include <Arduino.h>', '',
    'const uint8_t PETME_DATA[] PROGMEM = {',
]
for i in range(0, len(data), 24):
    lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
lines += ['};', f'const uint32_t PETME_LEN = {len(data)};   // {len(data) / 22050:.3f} s', '', '#endif']
open(header, "w").write("\n".join(lines) + "\n")
print(f"{len(data)} samples, {len(data) / 22050:.3f} s -> {header}")
